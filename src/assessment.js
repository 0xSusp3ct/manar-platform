export function getStructure(profile = 'current50') {
  const safeProfile = profile === 'guide48' ? 'guide48' : 'current50';
  return domains.map((domain) => ({
    ...domain,
    axes: domain.axes.map((axis) => ({
      ...axis,
      indicators: axis.indicators.filter((item) => item.profile === 'all' || item.profile === safeProfile)
    }))
  }));
}

export function calculateAssessment(answers, profile = 'current50') {
  const structure = getStructure(profile);
  const expected = structure.flatMap((domain) => domain.axes.flatMap((axis) => axis.indicators));
  const normalized = {};
  for (const indicator of expected) {
    const value = Number(answers[indicator.id]);
    if (!Number.isInteger(value) || value < 1 || value > 5) {
      throw new Error(`INVALID_ANSWER_${indicator.id}`);
    }
    normalized[indicator.id] = value;
  }

  const axes = [];
  const domainResults = [];
  const strengths = [];
  const opportunities = [];

  for (const domain of structure) {
    let domainPoints = 0;
    let domainCount = 0;
    for (const axis of domain.axes) {
      const points = axis.indicators.reduce((sum, item) => sum + normalized[item.id], 0);
      const percent = (points / (axis.indicators.length * 5)) * 100;
      axes.push({ id: axis.id, title: axis.title, domainId: domain.id, points, maxPoints: axis.indicators.length * 5, percent });
      domainPoints += points;
      domainCount += axis.indicators.length;
      for (const item of axis.indicators) {
        const score = normalized[item.id];
        const row = { id: item.id, title: item.title, description: item.description, score, axis: axis.title, domain: domain.shortTitle };
        if (score >= 4) strengths.push(row);
        if (score <= 2) opportunities.push(row);
      }
    }
    const percent = (domainPoints / (domainCount * 5)) * 100;
    domainResults.push({
      id: domain.id,
      title: domain.shortTitle,
      points: domainPoints,
      maxPoints: domainCount * 5,
      percent,
      weight: domain.weight
    });
  }

  const rawPoints = domainResults.reduce((sum, row) => sum + row.points, 0);
  const maxPoints = domainResults.reduce((sum, row) => sum + row.maxPoints, 0);
  const weightedPercent = domainResults.reduce((sum, row) => sum + row.percent * row.weight, 0);
  const overallPercent = profile === 'guide48' ? (rawPoints / 240) * 100 : weightedPercent;

  let maturity;
  if (profile === 'guide48') {
    maturity = rawPoints < 90 ? 'التأسيس' : rawPoints <= 160 ? 'الانطلاق' : rawPoints <= 205 ? 'النضج' : 'التميز';
  } else {
    maturity = weightedPercent < 37.5 ? 'التأسيس' : weightedPercent < 66.67 ? 'الانطلاق' : weightedPercent < 85.42 ? 'النضج' : 'التميز';
  }

  const recommendations = {
    'التأسيس': 'الأولوية هي بناء البنية الأساسية، وتوثيق اللوائح والسياسات، وتحديد مسؤوليات القياس والمتابعة.',
    'الانطلاق': 'يوجد أساس جيد يحتاج إلى تفعيل أكثر انتظامًا، وربط التنفيذ بمؤشرات واضحة لقياس النتائج والأثر.',
    'النضج': 'الأداء المؤسسي مستقر؛ وينبغي أن تركز المرحلة التالية على الابتكار، والتحسين المبني على البيانات، وتعظيم العائد المجتمعي.',
    'التميز': 'الجهة في مستوى ريادي؛ وتتمثل الأولوية في استدامة التميز، وتوثيق المعرفة، ونقل الممارسات الناجحة إلى الجهات الأخرى.'
  };

  return {
    profile,
    indicatorCount: expected.length,
    rawPoints,
    maxPoints,
    overallPercent: Number(overallPercent.toFixed(1)),
    maturity,
    systemRecommendation: recommendations[maturity],
    domains: domainResults.map((row) => ({ ...row, percent: Number(row.percent.toFixed(1)) })),
    axes: axes.map((row) => ({ ...row, percent: Number(row.percent.toFixed(1)) })),
    strengths,
    opportunities,
    answers: normalized
  };
}
